// Translation review status. Hindi and Tamil text was written without a native-speaker review, and the app says so.
export type Lang2 = "hi" | "ta";

export interface KeyReview {
  needsNativeReview: boolean;
  reviewedBy?: string;
  reviewedOn?: string;
}
export interface ReviewStatus {
  note: string;
  hi: Record<string, KeyReview>;
  ta: Record<string, KeyReview>;
}

export const REVIEW_NOTE =
  "Every Hindi and Tamil string is machine-assisted or author-written and has NOT been reviewed by a native speaker. needsNativeReview stays true until a named reviewer signs a key off by hand.";

/** Every key present in a dictionary gets an entry; a real sign-off in `prev` is kept; nothing is ever marked reviewed here. */
export function updateReviewStatus(dicts: Record<Lang2, Record<string, string>>, prev?: ReviewStatus): ReviewStatus {
  const out: ReviewStatus = { note: REVIEW_NOTE, hi: {}, ta: {} };
  for (const l of ["hi", "ta"] as const) {
    for (const key of Object.keys(dicts[l]).sort()) {
      const was = prev?.[l]?.[key];
      out[l][key] = was && was.needsNativeReview === false && was.reviewedBy && was.reviewedOn ? was : { needsNativeReview: true };
    }
  }
  return out;
}

export function renderTranslationDoc(s: ReviewStatus): string {
  const stat = (l: Lang2) => {
    const all = Object.values(s[l]);
    return { total: all.length, pending: all.filter((x) => x.needsNativeReview).length };
  };
  const hi = stat("hi");
  const ta = stat("ta");
  return `# Translation review status

> Generated by \`npm run docs:translation\` from \`src/i18n/*.json\`. The per-key status is \`src/i18n/review-status.json\`.

## Read this first

- **Hindi and Tamil text has not been reviewed by a native speaker.** It was written by the build agent. It may be stiff, wrong in tone, or wrong in meaning, and for money matters that is a real risk.
- The app does not claim otherwise: Settings says "Hindi and Tamil text are pending native-speaker review."
- A test (\`tests/i18n-parity.test.ts\`) checks that every English key exists in both languages and that **numbers and placeholders match** across languages. That catches a missing or altered figure. It says nothing about whether the language is good.

## Status

| Language | Keys | Pending native review | Reviewed |
|---|---|---|---|
| Hindi | ${hi.total} | ${hi.pending} | ${hi.total - hi.pending} |
| Tamil | ${ta.total} | ${ta.pending} | ${ta.total - ta.pending} |

## Who must do this

A native Hindi speaker and a native Tamil speaker, each with some financial literacy, should read every string on its screen. They should check meaning, tone, grade-8 reading level, and that the number and safety wording is still correct. The sentences the product is required to show (the demo notice, the adviser line, the draft warning) matter most and should be checked first.

## How to record a review

Edit the key's entry in \`src/i18n/review-status.json\` by hand:

\`\`\`json
"adv.approve": { "needsNativeReview": false, "reviewedBy": "Name, role", "reviewedOn": "2026-01-31" }
\`\`\`

\`npm run docs:translation\` keeps that entry and regenerates the rest. It never marks a key reviewed.

## What is not covered

Voice input (browser speech recognition) behaviour in Hindi and Tamil, AI-written text in those languages (see \`docs/live-smoke.md\` once a live run exists), and the romanised scam-message wording in \`tests/fixtures/scam-corpus.json\`.
`;
}
