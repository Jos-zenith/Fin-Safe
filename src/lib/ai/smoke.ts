// Live smoke run: sends every task, for Priya, in English, Hindi and Tamil, through the SAME pipeline the app
// uses, and records what happened. The report (docs/live-smoke.md) is only ever written after a run against a
// real provider. This module never sees or prints a key, and the report holds no profile data, no model text and
// no model id (the model id lives only in the AI_MODEL environment variable).
import { PRIYA } from "@/data/personas";
import { SAMPLES } from "@/data/samples";
import type { Lang } from "@/types";
import { runTask, type TaskRequest } from "./run";
import type { LLM } from "./providers";
import type { TaskName } from "./schemas";

export const SMOKE_TASKS: TaskName[] = ["explainFindings", "draftPlanPack", "adviserCopilot", "nudgeCopy", "answerQuestion", "secondOpinion"];
export const SMOKE_LANGS: Lang[] = ["en", "hi", "ta"];

export const NOT_EXERCISED = "Live path not exercised; run npm run smoke:live with your key.";

export function smokeRequests(): TaskRequest[] {
  const scam = SAMPLES.find((s) => s.id === "guaranteed_monthly")?.text ?? SAMPLES[0].text;
  return SMOKE_LANGS.flatMap((language) => [
    { task: "explainFindings", language, profile: PRIYA },
    { task: "draftPlanPack", language, profile: PRIYA },
    { task: "adviserCopilot", language, profile: PRIYA },
    { task: "nudgeCopy", language, profile: PRIYA, nudge: { ruleId: "ef_low" } },
    { task: "answerQuestion", language, profile: PRIYA, question: "How is my emergency fund?" },
    { task: "secondOpinion", language, text: scam },
  ] as TaskRequest[]);
}

export interface SmokeRow {
  task: TaskName;
  lang: Lang;
  source: "mock" | "provider" | "fixture";
  latencyMs: number;
  /** Event kinds only (never the details, which can quote model text). */
  kinds: string[];
}

export async function runSmoke(llm: LLM, opts: { timeoutMs?: number; onRow?: (r: SmokeRow) => void } = {}): Promise<SmokeRow[]> {
  const rows: SmokeRow[] = [];
  for (const req of smokeRequests()) {
    const t0 = Date.now();
    let row: SmokeRow;
    try {
      const out = await runTask(req, { llm, timeoutMs: opts.timeoutMs ?? 30_000 });
      row = { task: req.task, lang: req.language, source: out.source, latencyMs: out.latencyMs, kinds: out.events.map((e) => e.kind) };
    } catch {
      row = { task: req.task, lang: req.language, source: "fixture", latencyMs: Date.now() - t0, kinds: ["task_failed"] };
    }
    rows.push(row);
    opts.onRow?.(row);
  }
  return rows;
}

const median = (xs: number[]) => {
  if (!xs.length) return 0;
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : Math.round((s[m - 1] + s[m]) / 2);
};

export interface TaskSummary {
  task: TaskName;
  calls: number;
  kept: number;
  p50: number;
  max: number;
  schemaInvalid: number;
  numericRejected: number;
  guardrail: number;
  providerError: number;
  fallback: number;
}

export function summarise(rows: SmokeRow[]): TaskSummary[] {
  return SMOKE_TASKS.map((task) => {
    const r = rows.filter((x) => x.task === task);
    const n = (k: string) => r.reduce((a, x) => a + x.kinds.filter((y) => y === k).length, 0);
    return {
      task,
      calls: r.length,
      kept: r.filter((x) => x.source === "provider").length,
      p50: median(r.map((x) => x.latencyMs)),
      max: Math.max(0, ...r.map((x) => x.latencyMs)),
      schemaInvalid: n("schema_invalid"),
      numericRejected: n("numeric_rejected"),
      guardrail: n("guardrail"),
      providerError: n("provider_error"),
      fallback: n("fallback"),
    };
  });
}

/** PASS only if every task produced at least one answer from the model that survived validation. */
export function passed(rows: SmokeRow[]): boolean {
  return summarise(rows).every((s) => s.kept > 0);
}

export function renderSmokeDoc(rows: SmokeRow[], meta: { provider: string; at: string }): string {
  const sum = summarise(rows);
  const ok = passed(rows);
  const kept = rows.filter((r) => r.source === "provider").length;
  const pct = (a: number, b: number) => (b === 0 ? "n/a" : `${Math.round((a / b) * 100)}%`);
  const byLang = SMOKE_LANGS.map((l) => {
    const r = rows.filter((x) => x.lang === l);
    return `| ${l} | ${r.length} | ${r.filter((x) => x.source === "provider").length} | ${pct(r.filter((x) => x.source === "provider").length, r.length)} |`;
  }).join("\n");
  return `# Live AI smoke run

> Generated by \`npm run smoke:live\`. It exists only because someone ran it with a real key. Do not edit by hand.
> The report records counts and timings only: no key, no model id (that lives in \`AI_MODEL\`), no profile data, no model text.

- Run at: ${meta.at}
- Provider: ${meta.provider}
- Persona: the synthetic "Priya" profile, in English, Hindi and Tamil. ${rows.length} requests across ${SMOKE_TASKS.length} tasks.
- **Result: ${ok ? "PASS" : "FAIL"}**. PASS means every task produced at least one answer from the model that survived the schema, number and safety checks. It does not mean the answers are good.
- Answers kept from the model: ${kept}/${rows.length} (${pct(kept, rows.length)}). The rest were replaced by the validated pre-written fixture.

## By task

| task | calls | kept from model | success | p50 ms | max ms | schema failures | numeric rejections | guardrail rejections | provider errors | fallbacks |
|---|---|---|---|---|---|---|---|---|---|---|
${sum.map((s) => `| ${s.task} | ${s.calls} | ${s.kept} | ${pct(s.kept, s.calls)} | ${s.p50} | ${s.max} | ${s.schemaInvalid} | ${s.numericRejected} | ${s.guardrail} | ${s.providerError} | ${s.fallback} |`).join("\n")}

## By language

| language | calls | kept from model | success |
|---|---|---|---|
${byLang}

## What this does and does not show

- It shows the live path ran end to end against a real provider on this date, and how often the pipeline's own checks accepted the model's answer.
- It does **not** measure quality, accuracy, tone, or whether Hindi and Tamil text is natural. Those need a human reviewer, and Hindi and Tamil need native speakers.
- One run is a sample. Latency depends on the provider, the region and the day. Re-run before relying on any number here.
`;
}
