// The documents the brief asks for exist, say plainly what they do not show, and the repository carries no
// registration number, no real-adviser claim and no invented result.
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

const root = path.resolve(__dirname, "..");
const read = (rel: string) => readFileSync(path.join(root, rel), "utf8").replace(/\r\n/g, "\n");

describe("documents exist and state their limits", () => {
  const docs: [string, RegExp[]][] = [
    ["README.md", [/What is real, simulated and not built/, /primary customer is an advisory firm/, /Demo authentication\. Not secure authentication/, /Understand\*\* .*Plan\*\* .*Review\*\* .*Improve/s, /AI status/]],
    ["docs/PRODUCTION_GAP.md", [/no legal conclusions/i, /registered adviser|regulated entity/i, /suitability/i, /DPDP/, /IRDAI/, /security audit|Security review/i, /retention/i, /managed Postgres/i]],
    ["docs/ASSUMPTIONS.md", [/demo placeholder/i, /TO_VERIFY/, /Taxes are not included/i]],
    ["docs/scam-eval.md", [/synthetic/i, /optimistic/i, /not evidence/i, /held-out/i]],
    ["docs/translation-review.md", [/has not been reviewed by a native speaker/i]],
    ["docs/PILOT_PLAN.md", [/No pilot has been run/i, /Demo data\. Not evidence\./, /Preconditions/]],
    ["docs/DRAWBACK_REGISTER.md", [/DONE \(verified\)/, /DONE \(not verifiable here\)/, /PARTIAL/, /NOT DONE/]],
  ];
  for (const [file, patterns] of docs) {
    it(`${file}`, () => {
      expect(existsSync(path.join(root, file)), file).toBe(true);
      const text = read(file);
      for (const p of patterns) expect(text, `${file} ${p}`).toMatch(p);
    });
  }

  it("docs/live-smoke.md exists only after a real run, and then says so; otherwise the README admits the live path was not run", () => {
    if (existsSync(path.join(root, "docs/live-smoke.md"))) expect(read("docs/live-smoke.md")).toMatch(/Generated by `npm run smoke:live`/);
    else expect(read("README.md")).toContain("Live path not exercised; run npm run smoke:live with your key.");
  });

  it("layout screenshots exist at 360, 768, 1280 and 1536 px for the main screens", () => {
    for (const page of ["landing", "home", "plan", "adviser", "check"]) for (const w of [360, 768, 1280, 1536]) expect(existsSync(path.join(root, `docs/screenshots/${page}-${w}.png`)), `${page}-${w}`).toBe(true);
  });

  it("the README table says the AI is simulated by default and states the live-run status consistently with docs/live-smoke.md", () => {
    const readme = read("README.md");
    expect(readme).toMatch(/\*\*Simulated by default\*\*/);
    if (existsSync(path.join(root, "docs/live-smoke.md"))) expect(readme).toMatch(/was \*\*run once\*\*/);
    else expect(readme).toMatch(/has \*\*never been run\*\*/);
  });
});

describe("no registration number and no real-adviser claim anywhere", () => {
  const walk = (dir: string, out: string[] = []): string[] => {
    for (const f of readdirSync(dir)) {
      if (["node_modules", ".next", ".git", "test-results", "screenshots"].includes(f) || f.startsWith(".next-") || f.startsWith(".data")) continue;
      const p = path.join(dir, f);
      if (statSync(p).isDirectory()) walk(p, out);
      else if (/\.(ts|tsx|json|md|yml)$/.test(f) && f !== "package-lock.json") out.push(p);
    }
    return out;
  };
  const files = walk(root);

  it("contains no INA/INH/INP/INZ-style registration number", () => {
    for (const f of files) expect(readFileSync(f, "utf8"), path.relative(root, f)).not.toMatch(/\bIN[AHPZM]\d{8,}\b/);
  });
  it("never shows a registration NUMBER for the synthetic adviser or anyone else", () => {
    for (const f of files) {
      const text = readFileSync(f, "utf8");
      expect(text, path.relative(root, f)).not.toMatch(/(?:SEBI\s+)?registration\s+(?:no\.?|number)\s*[:#-]?\s*[A-Z]{2,4}[\s-]?\d{5,}/i);
    }
  });
  it("never says the adviser is a real registered adviser, only that this is a synthetic persona", () => {
    const adviser = read("src/data/adviser.ts");
    expect(adviser).toMatch(/not a real SEBI-registered adviser/);
    expect(adviser).not.toMatch(/\bregistered investment adviser\b(?! )|licen[cs]e number/i);
  });
});
